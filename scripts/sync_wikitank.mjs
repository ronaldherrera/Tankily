import fs from 'fs';
import path from 'path';

const WIKI_DIR = 'WikiTank';
const OUTPUT_FILE = 'src/lib/wikiData.js';

function findFirstImage(children) {
  for (const child of children) {
    if (child.previewImage) return child.previewImage;
    if (child.children && child.children.length > 0) {
      const found = findFirstImage(child.children);
      if (found) return found;
    }
  }
  return null;
}

function getWikiTree(dir, relativePath = '') {
  const currentPath = path.join(dir, relativePath);
  if (!fs.existsSync(currentPath)) return { children: [] };
  
  const items = fs.readdirSync(currentPath, { withFileTypes: true });
  
  const folders = items.filter(item => item.isDirectory() && !['imagenes', 'images', '.next'].includes(item.name.toLowerCase()));
  const mdFiles = items.filter(item => item.isFile() && item.name.endsWith('.md'))
    .sort((a, b) => a.name.localeCompare(b.name));

  // Collect all MD files in the folder
  const contentFiles = mdFiles.map(file => path.join(relativePath, file.name).replace(/\\/g, '/'));

  const children = folders.map(folder => {
    const folderName = folder.name;
    const folderRelativePath = path.join(relativePath, folderName);
    const subTree = getWikiTree(dir, folderRelativePath);
    
    const slug = folderName.toLowerCase()
      .normalize("NFD").replace(/[\u0300-\u036f]/g, "")
      .replace(/[^a-z0-9\s-]/g, "")
      .trim()
      .replace(/\s+/g, '-');

    // Intentar encontrar una imagen de vista previa para esta carpeta
    const folderPath = path.join(currentPath, folderName);
    let previewImage = null;

    // Buscar en:
    // 1. La misma carpeta del folder (ej: FolderName/FolderName.webp)
    // 2. Una subcarpeta 'Imagenes' o 'images' dentro del folder
    const searchDirs = [folderPath, path.join(folderPath, 'Imagenes'), path.join(folderPath, 'images')];

    for (const sDir of searchDirs) {
      if (fs.existsSync(sDir) && fs.lstatSync(sDir).isDirectory()) {
        const files = fs.readdirSync(sDir);
        
        // Filtrar archivos de imagen
        const imageFiles = files.filter(file => {
          const ext = path.extname(file).toLowerCase();
          return ['.webp', '.jpg', '.jpeg', '.png', '.svg'].includes(ext);
        });

        if (imageFiles.length > 0) {
          // 1. Intentar coincidencia exacta o por slug
          let imageMatch = imageFiles.find(file => {
            const fileName = path.parse(file).name.toLowerCase().replace(/_/g, '-').replace(/\s+/g, '-');
            const sanitizedFolderName = folderName.toLowerCase().replace(/_/g, '-').replace(/\s+/g, '-');
            return fileName === slug || fileName === sanitizedFolderName;
          });

          // 2. Si no hay coincidencia exacta, usar la primera imagen encontrada
          if (!imageMatch) {
            imageMatch = imageFiles[0];
          }

          if (imageMatch) {
            const imageRelativePath = path.join(folderRelativePath, sDir === folderPath ? '' : path.basename(sDir), imageMatch);
            previewImage = imageRelativePath.replace(/\\/g, '/');
            break;
          }
        }
      }
    }

    return {
      title: folderName.replace(/_/g, ' ').toUpperCase(),
      slug: slug,
      previewImage: previewImage || findFirstImage(subTree.children),
      relativePath: folderRelativePath.replace(/\\/g, '/'),
      contentFiles: subTree.contentFiles,
      children: subTree.children
    };
  });

  return {
    contentFiles: contentFiles,
    children: children
  };
}

const tree = getWikiTree(WIKI_DIR);

const content = `// Autogenerated WikiTank Data - DO NOT EDIT MANUALLY
export const wikiTankTree = ${JSON.stringify(tree.children, null, 2)};
`;

fs.writeFileSync(OUTPUT_FILE, content);

// Copiar WikiTank a public/wiki-media
const publicMediaDir = path.join(process.cwd(), 'public', 'wiki-media');
if (fs.existsSync(publicMediaDir)) {
  fs.rmSync(publicMediaDir, { recursive: true, force: true });
}
fs.mkdirSync(publicMediaDir, { recursive: true });
fs.cpSync(WIKI_DIR, publicMediaDir, { recursive: true });

console.log('✅ WikiTank data synchronized and media copied to public/wiki-media successfully!');
