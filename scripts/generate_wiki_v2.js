const fs = require('fs');
const path = require('path');

const WIKI_DIR = path.join(__dirname, '../wiki-contenido');
const OUTPUT_FILE = path.join(__dirname, '../src/lib/wikiData.js');
const TREE_FILE = path.join(WIKI_DIR, '00_ARBOL_NAVEGACION.md');

function slugify(text) {
  return text
    .toString()
    .toLowerCase()
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^\w-]+/g, '')
    .replace(/--+/g, '-');
}

function getColorForCategory(title) {
    const t = title.toLowerCase();
    if (t.includes('fundamentos')) return '#6b7280'; // Gris
    if (t.includes('tropical')) return '#10b981'; // Esmeralda
    if (t.includes('plantado')) return '#22c55e'; // Verde
    if (t.includes('discus')) return '#f59e0b'; // Ámbar
    if (t.includes('agua fría')) return '#06b6d4'; // Cian
    if (t.includes('biotopo')) return '#844d36'; // Marrón Biotopo
    if (t.includes('gambas')) return '#ec4899'; // Rosa
    if (t.includes('fowlr')) return '#6366f1'; // Índigo
    if (t.includes('arrecife') || t.includes('reef')) return '#8b5cf6'; // Violeta
    if (t.includes('salobre')) return '#94a3b8'; // Pizarra
    if (t.includes('paludarium')) return '#14b8a6'; //Teal
    if (t.includes('referencias')) return '#475569'; // Azul grisáceo
    return '#3b82f6'; // Azul por defecto
}

function parseTree() {
  const content = fs.readFileSync(TREE_FILE, 'utf8');
  const lines = content.split('\n');
  const groups = [];
  let currentGroup = null;
  let currentCategory = null;
  let inTreeBlock = false;

  lines.forEach(line => {
    // Detect Groups (Headers Level 1)
    if (line.startsWith('# ') && !line.includes('TANKILY')) {
        currentGroup = {
            title: line.replace('# ', '').trim(),
            categories: []
        };
        groups.push(currentGroup);
    }

    // Detect categories (Headers Level 2)
    if (line.startsWith('## ')) {
        const catName = line.replace('## ', '').trim();
        if (!catName.startsWith('NIVEL')) {
            currentCategory = {
                title: catName,
                slug: slugify(catName),
                color: getColorForCategory(catName),
                items: []
            };
            if (currentGroup) {
              currentGroup.categories.push(currentCategory);
            } else {
              const general = { title: 'GENERAL', slug: 'general', categories: [currentCategory] };
              groups.push(general);
              currentGroup = general;
            }
        }
    }

    // Detect tree blocks
    if (line.startsWith('```')) {
        inTreeBlock = !inTreeBlock;
        return;
    }

    if (inTreeBlock && currentCategory) {
        const match = line.match(/(?:├──|└──|│\s+├──|│\s+└──|│|─)\s*([^→\n]+)(?:→\s*([\w.]+)\s*§\s*(.+))?/);
        
        if (match) {
            let name = match[1].trim();
            name = name.replace(/^[│├└───\s]+/, '').trim();
            const file = match[2] ? match[2].trim() : null;
            const section = match[3] ? match[3].trim() : null;

            if (file) {
                currentCategory.items.push({
                    name,
                    file: file.replace('.md', ''),
                    section: section,
                    slug: `${file.replace('.md', '')}#${slugify(section)}`
                });
            }
        }
    }
  });

  return groups;
}

function generateData() {
  console.log('Generating Wiki Data V2...');
  
  const files = fs.readdirSync(WIKI_DIR).filter(f => f.endsWith('.md') && !f.startsWith('00_'));
  const articles = {};

  files.forEach(file => {
    const slug = file.replace('.md', '');
    const content = fs.readFileSync(path.join(WIKI_DIR, file), 'utf8');
    
    // Extract title (first # header)
    const titleMatch = content.match(/^#\s+(.+)/m);
    const title = titleMatch ? titleMatch[1] : slug;

    articles[slug] = {
      title,
      content
    };
  });

  const tree = parseTree();

  const output = `// Autogenerated Wiki Data - DO NOT EDIT MANUALLY
export const wikiTree = ${JSON.stringify(tree, null, 2)};

export const wikiArticles = ${JSON.stringify(articles, null, 2)};
`;

  fs.writeFileSync(OUTPUT_FILE, output);
  console.log('Wiki Data V2 generated successfully!');
}

generateData();
